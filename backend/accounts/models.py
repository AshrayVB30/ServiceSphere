"""
Database Models for the 'accounts' application.

Defines the custom User model for ServiceSphere. By subclassing Django's
built-in AbstractUser, we retain all standard authentication features
(password hashing, permissions, groups, session tokens) while adding custom
business attributes: role-based access control and multi-tenant client organization linkage.
"""

from django.contrib.auth.models import AbstractUser
from django.db import models


class User(AbstractUser):
    """
    Custom User model representing every registered individual in ServiceSphere.
    
    Roles:
    - ADMIN: Full system administrator with access to all organizations and management APIs.
    - SUPPORT_AGENT: Internal support staff who handle and resolve customer tickets.
    - CLIENT: Customer employee who creates and tracks support tickets for their company.
    - APPROVER: Customer or internal manager who reviews and authorizes sensitive actions.
    """

    class Role(models.TextChoices):
        # Enumeration of allowed user roles.
        # Format: VARIABLE_NAME = "DATABASE_VALUE", "HUMAN_READABLE_LABEL"
        ADMIN = "ADMIN", "Administrator"
        SUPPORT_AGENT = "SUPPORT_AGENT", "Support Agent"
        CLIENT = "CLIENT", "Client"
        APPROVER = "APPROVER", "Approver"

    # Enforce unique email addresses across all accounts so email can serve as an identifier.
    email = models.EmailField(unique=True)

    # Assigns a role to the user to drive role-based permission logic across the system.
    # db_index=True creates a database B-tree index on this column for fast role filtering.
    role = models.CharField(
        max_length=20,
        choices=Role.choices,
        default=Role.CLIENT,
        db_index=True,
    )

    # Optional contact phone number for notifications or two-factor verification.
    phone_number = models.CharField(
        max_length=20,
        blank=True,
    )

    # Associates this user with a specific client organization.
    # - "clients.Client": Uses a lazy string reference to avoid circular import issues.
    # - on_delete=models.SET_NULL: If a client company is ever deleted, the user record is kept
    #   and their client field becomes NULL (preventing accidental cascade deletion of users).
    # - null=True, blank=True: Field is optional (System Admins and internal Agents don't belong to a client).
    # - related_name="users": Allows reverse querying (e.g. `client.users.all()`).
    client = models.ForeignKey(
        "clients.Client",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="users",
    )

    def __str__(self):
        """
        Human-readable string representation of a User object.
        Example output: 'john_doe (Client)'
        """
        # get_role_display() is automatically generated by Django for fields with 'choices'.
        return f"{self.username} ({self.get_role_display()})"
