"""
Django Admin Configuration for the 'knowledge_base' application.

Registers Category, Article, ArticleTicket, and ArticleRevision models with:
- Informative list columns, filters, and search capabilities.
- Read-only protection for revision history and immutable audit snapshots.
- Convenient category slug prepopulation and quick publication action shortcuts.
"""

from django.contrib import admin
from .models import Category, Article, ArticleTicket, ArticleRevision


@admin.register(Category)
class CategoryAdmin(admin.ModelAdmin):
    """Admin interface for Knowledge Base Categories."""

    list_display = (
        "id",
        "name",
        "slug",
        "is_active",
        "created_at",
        "updated_at",
    )
    list_filter = (
        "is_active",
        "created_at",
    )
    search_fields = (
        "name",
        "description",
        "slug",
    )
    prepopulated_fields = {
        "slug": ("name",),
    }
    ordering = ("name",)


class ArticleRevisionInline(admin.TabularInline):
    """Inline view of revision snapshots inside the Article admin page."""

    model = ArticleRevision
    extra = 0
    can_delete = False
    readonly_fields = (
        "revision_number",
        "previous_title",
        "previous_summary",
        "revised_by",
        "created_at",
    )
    fields = (
        "revision_number",
        "previous_title",
        "previous_summary",
        "revised_by",
        "created_at",
    )

    def has_add_permission(self, request, obj=None):
        """Revisions are auto-generated by the service layer, not created manually."""
        return False


class ArticleTicketInline(admin.TabularInline):
    """Inline view of linked tickets inside the Article admin page."""

    model = ArticleTicket
    extra = 0
    readonly_fields = (
        "ticket",
        "linked_by",
        "created_at",
    )
    fields = (
        "ticket",
        "linked_by",
        "created_at",
    )


@admin.register(Article)
class ArticleAdmin(admin.ModelAdmin):
    """Admin interface for Knowledge Base Articles."""

    list_display = (
        "id",
        "title",
        "category",
        "author",
        "status",
        "visibility",
        "published_at",
        "created_at",
    )
    list_filter = (
        "status",
        "visibility",
        "category",
        "created_at",
        "published_at",
    )
    search_fields = (
        "title",
        "summary",
        "content",
        "slug",
        "author__username",
        "author__email",
    )
    prepopulated_fields = {
        "slug": ("title",),
    }
    readonly_fields = (
        "published_at",
        "created_at",
        "updated_at",
    )
    inlines = [
        ArticleRevisionInline,
        ArticleTicketInline,
    ]
    ordering = ("-created_at",)


@admin.register(ArticleRevision)
class ArticleRevisionAdmin(admin.ModelAdmin):
    """Admin interface for Article Revision Snapshots (strictly read-only for audit integrity)."""

    list_display = (
        "id",
        "article",
        "revision_number",
        "previous_title",
        "revised_by",
        "created_at",
    )
    list_filter = (
        "created_at",
    )
    search_fields = (
        "previous_title",
        "previous_summary",
        "previous_content",
        "article__title",
        "revised_by__username",
    )
    readonly_fields = (
        "article",
        "revised_by",
        "revision_number",
        "previous_title",
        "previous_summary",
        "previous_content",
        "created_at",
    )

    def has_add_permission(self, request):
        return False

    def has_delete_permission(self, request, obj=None):
        return False


@admin.register(ArticleTicket)
class ArticleTicketAdmin(admin.ModelAdmin):
    """Admin interface for Ticket-Article linkages."""

    list_display = (
        "id",
        "article",
        "ticket",
        "linked_by",
        "created_at",
    )
    list_filter = (
        "created_at",
    )
    search_fields = (
        "article__title",
        "ticket__subject",
        "linked_by__username",
    )
    readonly_fields = (
        "created_at",
    )

