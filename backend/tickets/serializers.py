"""
REST API Serializers for the 'tickets' application.

This serializer handles:
1. Serialization: Converts Ticket model instances into JSON representations,
   enriching foreign key IDs with human-readable names (e.g. client company name, author username).
2. Deserialization & Security Validation: Restricts input fields on ticket creation so
   client users can only provide issue details ('subject', 'description', 'category', 'priority').
   Client identity, creator, assignment, and status are derived and secured server-side.
"""

from rest_framework import serializers
from .models import Ticket


class TicketSerializer(serializers.ModelSerializer):
    """
    ModelSerializer for Help Desk Tickets.
    """

    # Read-only convenience fields: Flatten foreign key relations into readable strings in JSON
    # 'source="client.name"' looks up the 'name' attribute on the related Client model
    client_name = serializers.CharField(
        source="client.name",
        read_only=True,
        help_text="Name of the client organization owning this ticket.",
    )

    # Username of the employee who submitted the ticket
    created_by_username = serializers.CharField(
        source="created_by.username",
        read_only=True,
        help_text="Username of the user who filed the ticket.",
    )

    # Username of the support agent assigned to the ticket (or None if unassigned)
    assigned_to_username = serializers.CharField(
        source="assigned_to.username",
        read_only=True,
        default=None,
        help_text="Username of the support agent currently assigned.",
    )

    class Meta:
        model = Ticket

        # All fields included in the JSON API representation
        fields = [
            "id",
            "ticket_number",
            "client",
            "client_name",
            "created_by",
            "created_by_username",
            "assigned_to",
            "assigned_to_username",
            "subject",
            "description",
            "category",
            "priority",
            "status",
            "created_at",
            "updated_at",
            "resolved_at",
        ]

        # Security-critical read-only fields:
        # These fields CANNOT be set or overwritten by users through incoming API request bodies.
        # - 'client' & 'created_by': Automatically assigned by the backend from request.user.
        # - 'assigned_to': Assigned only by managers/support agents via dedicated workflows.
        # - 'status': Initialized to 'OPEN' and modified only through controlled transitions.
        # - Timestamps and UUID: Auto-generated by the database.
        read_only_fields = [
            "id",
            "ticket_number",
            "client",
            "created_by",
            "assigned_to",
            "status",
            "created_at",
            "updated_at",
            "resolved_at",
        ]

